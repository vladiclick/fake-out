export function getRandomWord(deck: Deck, lang: string): { word: string; hint: string; wordObj: DeckWord } {
  const wordObj = deck.words[Math.floor(Math.random() * deck.words.length)];
  const ro = lang === 'ro';
  return {
    word: ro && wordObj.wro ? wordObj.wro : wordObj.w,
    hint: ro && wordObj.hro ? wordObj.hro : wordObj.h,
    wordObj,
  };
}

export function shuffle<T>(arr: T[]): T[] {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function formatTime(s: number): string {
  if (!Number.isFinite(s) || s < 0) return '0:00';
  return Math.floor(s / 60) + ':' + String(Math.floor(s) % 60).padStart(2, '0');
}
